export const ALL_CYCLE_CODEBOOK_TEMPLATES: CycleCodebookTemplate[] = [
  ...FIRST_CYCLE_CODEBOOK_TEMPLATES,
  ...SECOND_CYCLE_CODEBOOK_TEMPLATES,
];

export function templatesForMethod(cycle: 1 | 2, methodId: string): CycleCodebookTemplate[] {
  const list = cycle === 1 ? FIRST_CYCLE_CODEBOOK_TEMPLATES : SECOND_CYCLE_CODEBOOK_TEMPLATES;
  return list.filter((t) => t.methodId === methodId);
}

export function templateById(id: string): CycleCodebookTemplate | undefined {
  return ALL_CYCLE_CODEBOOK_TEMPLATES.find((t) => t.id === id);
}

/** 빈 AI 초안 기입 폼 */
export type FirstCycleDraftForm = Record<string, string>;
export type SecondCycleDraftForm = Record<string, string>;

export function emptyFirstDraftForm(): FirstCycleDraftForm {
  const o: FirstCycleDraftForm = {};
  FIRST_CYCLE_DRAFT_FIELDS.forEach((f) => { o[f.key] = ""; });
  return o;
}

export function emptySecondDraftForm(): SecondCycleDraftForm {
  const o: SecondCycleDraftForm = {};
  SECOND_CYCLE_DRAFT_FIELDS.forEach((f) => { o[f.key] = ""; });
  return o;
}

export function describeSelectedMethods(cycle: 1 | 2, ids: string[]): string {
  const src = cycle === 1 ? FIRST_CYCLE_METHODS : SECOND_CYCLE_METHODS;
  return ids
    .map((id) => src.find((m) => m.id === id))
    .filter(Boolean)
    .map((m) => `${m!.label}(${m!.labelEn})`)
    .join(", ");
}
