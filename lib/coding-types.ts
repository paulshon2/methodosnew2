/**
 * 코딩 스튜디오의 자료 구조 — 순수 함수만 둔다.
 *
 * 핵심 결정: 코딩 단위를 문장으로 고정한다.
 * 임의 범위를 끌어 지정하면 코더마다 범위가 달라져 일치도(κ)를 계산할 수 없고,
 * 키보드만으로는 조작할 수 없다. 단위를 고정하면 그 두 문제가 함께 풀린다.
 */

export type Who = "R" | "P";

export type Seg = { id: string; text: string; turn: number; who: Who };
export type Turn = { who: Who; text: string; segIds: string[] };
/** kind는 자료의 갈래(심층면담·관찰노트·개방형 설문…). 갈래가 다르면 읽는 법도 달라진다. */
export type Doc = { id: string; kind: string; title: string; meta: string; turns: Turn[]; segs: Seg[] };
export type Code = { id: string; name: string; color: string; memo: string };
export type Theme = { id: string; name: string; open: boolean; codes: Code[] };
/** segId → codeId[] */
export type Assign = Record<string, string[]>;

/** 색각 이상에서도 구별되는 Okabe–Ito 계열. 코드 색은 여기서만 고른다. */
