/** 마침표·물음표·느낌표 뒤에서 끊는다. 약어까지 다루지 않는 것은 전사본에 거의 없기 때문이다. */
export function splitSentences(text: string): string[] {
  return text
    .split(/(?<=[.?!。？！])\s+/)
    .map((s) => s.trim())
    .filter(Boolean);
}

/** 발화 목록을 문장 단위로 쪼개 Doc을 만든다. */
export function buildDoc(id: string, title: string, meta: string, raw: [Who, string][], kind = "심층면담"): Doc {
  const segs: Seg[] = [];
  const turns: Turn[] = raw.map(([who, text], ti) => {
    const segIds = splitSentences(text).map((part) => {
      const sid = `${id}-${segs.length}`;
      segs.push({ id: sid, text: part, turn: ti, who });
      return sid;
    });
    return { who, text, segIds };
  });
  return { id, kind, title, meta, turns, segs };
}

export const allCodes = (themes: Theme[]): Code[] => themes.flatMap((t) => t.codes);
export const codeById = (themes: Theme[], id: string): Code | undefined => allCodes(themes).find((c) => c.id === id);
/** 1~9 단축키 번호. 10번째부터는 번호가 없다 — 숫자키가 아홉 개뿐이기 때문이다. */
export const keyOf = (themes: Theme[], id: string): number => allCodes(themes).findIndex((c) => c.id === id) + 1;

/** 참여자 발화만 분모로 센다. 연구자의 질문은 코딩 대상이 아니다. */
export function progress(docs: Doc[], a: Assign): { total: number; coded: number; pct: number; applied: number } {
  const target = docs.flatMap((d) => d.segs).filter((s) => s.who === "P");
  const coded = target.filter((s) => (a[s.id] ?? []).length > 0).length;
  const applied = Object.values(a).reduce((n, cs) => n + cs.length, 0);
  return { total: target.length, coded, pct: target.length ? Math.round((coded / target.length) * 100) : 0, applied };
}

/** 코드별 적용 횟수 — 코드북의 빈도 막대에 쓴다. */
export function codeCounts(a: Assign): Record<string, number> {
  const out: Record<string, number> = {};
  Object.values(a).forEach((cs) => cs.forEach((c) => (out[c] = (out[c] ?? 0) + 1)));
  return out;
}

/**
 * 코딩 결과 CSV.
 * 앞머리 BOM이 없으면 Excel이 한글을 깨뜨린다.
 */
export function codingCsv(docs: Doc[], themes: Theme[], a: Assign): string {
  const rows: string[][] = [["자료", "발화자", "문장", "코드"]];
  docs.forEach((d) =>
    d.segs.forEach((s) =>
      rows.push([
        d.title,
        s.who === "R" ? "연구자" : "참여자",
        s.text,
        (a[s.id] ?? []).map((c) => codeById(themes, c)?.name ?? c).join("; "),
      ]),
    ),
  );
  return "\uFEFF" + rows.map((r) => r.map((v) => `"${v.replace(/"/g, '""')}"`).join(",")).join("\n");
}

