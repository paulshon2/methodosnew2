def task_step_annotations(stage_i, task_i, proc_paras, analysis_key, topic, method_name=""):
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out = []
    for i in range(n):
        step = proc_paras[i] if i < len(proc_paras) else ""
        note = bank[i] if i < len(bank) else (
            f"이 단계({stage_i+1}단계·태스크 {task_i+1}의 {i+1}번째 절차)를 문서화해 재현합니다."
        )
        parts = [note]
        if i == 0 and topic.get("title"):
            parts.append(
                f"본 주제 「{topic['title']}」(과정: {topic.get('process','')}, "
                f"전통: {topic.get('tradition','')})에 맞춰 읽습니다."
            )
        extra = _terms(step)
        if extra:
            parts.append(" ".join(extra[:3]))
        key = analysis_key.lower()
        if i == 0:
            if key.startswith("str_"):
                parts.append("스트라우스 계열은 패러다임 모형(인과·맥락·중재·전략·결과)을 명시적으로 채웁니다.")
            elif key.startswith("cgz_") or key.startswith("cgt_"):
                parts.append("구성주의/구축적 GT는 연구자·참여자의 공동구성과 위치성 성찰을 강조합니다.")
            elif key.startswith("gt2"):
                parts.append("2세대·재검토는 표집·메모·포화의 방법적 투명성을 특히 문서화합니다.")
        out.append("\n".join(parts))
    return out
