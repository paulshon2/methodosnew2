def task_step_annotations(stage_i, task_i, proc_paras, analysis_key, topic, method_name=""):
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out = []
    for i in range(n):
        step = proc_paras[i] if i < len(proc_paras) else ""
        note = bank[i] if i < len(bank) else (
            f"이 단계({stage_i+1}단계·태스크 {task_i+1}의 {i+1}번째 절차) 입력→처리→출력을 남겨 재현합니다."
        )
        parts = [note]
        if i == 0 and topic.get("title"):
            parts.append(
                f"본 주제 「{topic['title']}」(기준: {topic.get('criteria','')}, 모드: {topic.get('mode','')})에 맞춰 읽습니다."
            )
        extra = _terms(step)
        if extra:
            parts.append(" ".join(extra[:3]))
        key = analysis_key.lower()
        if i == 0:
            if key.startswith("delphi"):
                parts.append("델파이 주제는 ‘합의 과정(라운드·IQR)’ 자체가 핵심 결과물입니다.")
            elif key.startswith("ahp"):
                parts.append("AHP 주제는 쌍대비교 행렬·CR·가중치 표가 재현의 핵심입니다.")
            elif key.startswith("cba"):
                parts.append("CBA 주제는 가정·할인율·민감도 없이 BCR만 제시하면 안 됩니다.")
            elif key.startswith("ie_"):
                parts.append("영향평가 주제는 비교집단·식별전략(DiD 등)을 방법란에 명확히 적습니다.")
            elif key.startswith("ufe_"):
                parts.append("UFE 주제는 이용자·활용 계획이 평가설계의 출발점입니다.")
        out.append("\n".join(parts))
    return out
