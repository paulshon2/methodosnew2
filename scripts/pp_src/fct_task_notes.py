def task_step_annotations(stage_i, task_i, proc_paras, analysis_key, topic, method_name=""):
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out = []
    for i in range(n):
        step = proc_paras[i] if i < len(proc_paras) else ""
        note = bank[i] if i < len(bank) else (
            f"이 단계({stage_i+1}단계·태스크 {task_i+1}의 {i+1}번째 절차)를 문서화해 재현합니다."
        )
        parts = [note]
        if i == 0 and topic.get("title"):
            parts.append(
                f"본 주제 「{topic['title']}」(모드: {topic.get('mode','')}, "
                f"초점: {topic.get('focus','')})에 맞춰 읽습니다."
            )
        extra = _terms(step)
        if extra:
            parts.append(" ".join(extra[:3]))
        key = analysis_key.lower()
        if i == 0:
            if key.startswith("dp_"):
                parts.append("규율권력 분석은 시간·공간·시선·기록의 배치를 우선 관찰합니다.")
            elif key.startswith("de_"):
                parts.append("QL-004은 합리성·해방 언어가 만드는 지배·물화 효과를 함께 읽습니다.")
            elif key.startswith("fa_"):
                parts.append("푸코적 분석은 담론·제도·실천의 결합으로 ‘정상’이 구성되는 방식을 추적합니다.")
            elif key.startswith("fp_"):
                parts.append("권력분석은 문제화·전문성·공간·자기통치의 효과를 구체적으로 매핑합니다.")
            elif key.startswith("fm_"):
                parts.append("분석방법 주제는 고고학·계보학·장치·주체화 절차의 투명한 적용을 강조합니다.")
        out.append("\n".join(parts))
    return out
