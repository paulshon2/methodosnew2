def task_step_annotations(stage_i, task_i, proc_paras, analysis_key, topic, method_name=""):
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out = []
    for i in range(n):
        step = proc_paras[i] if i < len(proc_paras) else ""
        note = bank[i] if i < len(bank) else (
            f"이 단계({stage_i+1}단계·태스크 {task_i+1}의 {i+1}번째 절차)를 문서화해 재현합니다."
        )
        parts = [note]
        if i == 0 and topic.get("title"):
            parts.append(
                f"본 주제 「{topic['title']}」(설계모드: {topic.get('mode','')}, "
                f"초점: {topic.get('focus','')})에 맞춰 읽습니다."
            )
        extra = _terms(step)
        if extra:
            parts.append(" ".join(extra[:3]))
        key = analysis_key.lower()
        if i == 0:
            if key.startswith("mm_"):
                parts.append("혼합설계는 양·질 자료의 연결(통합) 지점을 설계서에 명시합니다.")
            elif key.startswith("ni_"):
                parts.append("자연주의 탐구는 조작·통제보다 자연상황·맥락 기술을 우선합니다.")
            elif key.startswith("ts_"):
                parts.append("이론적 민감성 주제는 메모·문헌·동료검토로 ‘보이는 눈’을 훈련합니다.")
            elif key.startswith("gl_"):
                parts.append("용어사전 주제는 정의·예시·오용주의·관련절차를 한 세트로 제시합니다.")
            elif key.startswith("qrd_"):
                parts.append("질적 연구설계 주제는 전통·질문·자료·표집의 정합표를 중심에 둡니다.")
        out.append("\n".join(parts))
    return out
