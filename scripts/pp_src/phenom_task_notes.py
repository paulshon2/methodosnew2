def task_step_annotations(stage_i, task_i, proc_paras, analysis_key, topic, method_name=""):
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out = []
    for i in range(n):
        step = proc_paras[i] if i < len(proc_paras) else ""
        note = bank[i] if i < len(bank) else (
            f"이 단계({stage_i+1}단계·태스크 {task_i+1}의 {i+1}번째 절차)를 문서화해 재현합니다."
        )
        parts = [note]
        if i == 0 and topic.get("title"):
            parts.append(
                f"본 주제 「{topic['title']}」(체험: {topic.get('lived','')}, 전통: {topic.get('tradition','')})에 맞춰 읽습니다."
            )
        extra = _terms(step)
        if extra:
            parts.append(" ".join(extra[:3]))
        key = analysis_key.lower()
        if i == 0:
            if key.startswith("hp_") or key.startswith("ipa_"):
                parts.append("해석학/IPA는 괄호넣기와 함께, 의미의 해석·개인 맥락을 더 전면에 둡니다.")
            elif key.startswith("hu_") or key.startswith("id_"):
                parts.append("순수현상학·이념들 계열은 지향성·환원·본질직관을 절차에 명시합니다.")
            elif key.startswith("pp_"):
                parts.append("지각 현상학은 몸·공간·지각 구조를 기술·해석의 중심에 둡니다.")
            elif key.startswith("dp_") or key.startswith("ph_") or key.startswith("prm_"):
                parts.append("기술 현상학은 주제·본질 도출에서 이론 과잉해석을 경계합니다.")
        out.append("\n".join(parts))
    return out
