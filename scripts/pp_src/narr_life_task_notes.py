def task_step_annotations(stage_i, task_i, proc_paras, analysis_key, topic, method_name=""):
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out = []
    for i in range(n):
        step = proc_paras[i] if i < len(proc_paras) else ""
        note = bank[i] if i < len(bank) else (
            f"이 단계({stage_i+1}단계·태스크 {task_i+1}의 {i+1}번째 절차)를 문서화해 재현합니다."
        )
        parts = [note]
        if i == 0 and topic.get("title"):
            parts.append(
                f"본 주제 「{topic['title']}」(생애호: {topic.get('life_arc','')}, "
                f"초점: {topic.get('focus','')})에 맞춰 읽습니다."
            )
        extra = _terms(step)
        if extra:
            parts.append(" ".join(extra[:3]))
        key = analysis_key.lower()
        if i == 0:
            if key.startswith("ni_"):
                parts.append("내러티브탐구는 시간·사회·장소의 3차원과 관계성을 서술·분석에 명시합니다.")
            elif key.startswith("na_"):
                parts.append("서사분석은 플롯·목소리·청자·평가 장치에 분석 초점을 둡니다.")
            elif key.startswith("tlh_"):
                parts.append("교사 생애사는 교직제도·학교문화와 개인 플롯을 교차시킵니다.")
            elif key.startswith(("hum_", "bio_")):
                parts.append("인문·전기 계열은 텍스트/공적 표상과 구술·사적 증언의 간극을 분석합니다.")
        out.append("\n".join(parts))
    return out
