def task_step_annotations(
    stage_i: int,
    task_i: int,
    proc_paras: list[str],
    analysis_key: str,
    topic: dict[str, Any],
    method_name: str = "",
) -> list[str]:
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out: list[str] = []
    for i in range(n):
        step = proc_paras[i] if i < len(proc_paras) else ""
        note = bank[i] if i < len(bank) else (
            f"이 단계({stage_i+1}단계·태스크 {task_i+1}의 {i+1}번째 절차) 입력→처리→출력을 문서화해 재현합니다."
        )
        parts = [note]
        if i == 0 and topic.get("title"):
            parts.append(
                f"본 주제 「{topic['title']}」(출처: {topic.get('source','')}, 파이프라인: {topic.get('pipeline','')})에 맞춰 읽습니다."
            )
        extra = _terms(step)
        if extra:
            parts.append(" ".join(extra[:3]))
        key = analysis_key.lower()
        if i == 0:
            if key.startswith("sna"):
                parts.append("연결망 주제는 ‘텍스트 내용’과 ‘누가 누구와 연결되는지’를 함께 봅니다.")
            elif key.startswith("tm_") or key.startswith("rtm_stm"):
                parts.append("토픽 주제는 라벨보다 ‘단어 묶음의 해석 가능성’이 핵심 산출입니다.")
            elif key.startswith("ir_"):
                parts.append("검색 주제는 분류 F1 대신 nDCG·MRR 같은 순위 지표를 중심에 둡니다.")
            elif key.startswith("dl_") or key.startswith("ai_"):
                parts.append("TX-003/AI 주제는 기준선(전통 ML)과 비교표를 반드시 남깁니다.")
        out.append("\n".join(parts))
    return out
