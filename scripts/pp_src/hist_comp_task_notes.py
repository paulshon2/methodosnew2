def task_step_annotations(
    stage_i: int,
    task_i: int,
    proc_paras: list[str],
    analysis_key: str,
    topic: dict[str, Any],
    method_name: str = "",
) -> list[str]:
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out: list[str] = []
    for i in range(n):
        step_text = proc_paras[i] if i < len(proc_paras) else ""
        if i < len(bank):
            note = bank[i]
        else:
            note = (
                f"이 단계({stage_i + 1}단계·태스크 {task_i + 1}의 {i + 1}번째 절차)에서는 위에 적힌 작업을 수행합니다. "
                "입력(이전 단계 산출물) → 절차 → 출력(표·목록·서술)을 문서에 남겨 재현 가능하게 합니다."
            )
        extra = _terms_from_step(step_text)
        aextra = _akey_extra(analysis_key, i)
        parts = [note]
        if aextra:
            parts.append(aextra)
        if extra:
            parts.append(" ".join(extra[:3]))
        # light topic hook
        if i == 0 and topic.get("title"):
            parts.append(f"본 주제 「{topic['title']}」의 초점({topic.get('focus', '')})에 맞춰 용어·사례를 읽습니다.")
        out.append("\n".join(parts))
    return out
