def task_step_annotations(
    stage_i: int,
    task_i: int,
    proc_paras: list[str],
    analysis_key: str,
    topic: dict[str, Any],
    method_name: str = "",
) -> list[str]:
    n = max(len(proc_paras), 1)
    bank = STEP_NOTE_BANK.get((stage_i, task_i), [])
    out: list[str] = []
    for i in range(n):
        step_text = proc_paras[i] if i < len(proc_paras) else ""
        if i < len(bank):
            note = bank[i]
        else:
            note = (
                f"이 단계({stage_i + 1}단계·태스크 {task_i + 1}의 {i + 1}번째 절차) 작업을 수행합니다. "
                "입력→절차→출력을 남겨 재현 가능하게 합니다."
            )
        extra = _terms_from_step(step_text)
        parts = [note]
        if topic.get("title") and i == 0:
            parts.append(f"본 주제 「{topic['title']}」(현장: {topic.get('site', '')})의 초점({topic.get('focus', '')})에 맞춰 읽습니다.")
        if extra:
            parts.append(" ".join(extra[:3]))
        if analysis_key.startswith("netn") and i == 0:
            parts.append("온라인 현장은 ‘공개 게시물’과 ‘비공개 메시지’의 윤리 기준이 다릅니다.")
        if analysis_key.startswith("meta_") and i == 0:
            parts.append("메타민족지는 새 현장 관찰 대신 기존 연구의 번역·합성이 자료입니다.")
        if analysis_key.startswith("argo_") and i == 0:
            parts.append("고전 텍스트 재독은 ‘원전 인용+현대적 방법 성찰’을 함께 적습니다.")
        out.append("\n".join(parts))
    return out
