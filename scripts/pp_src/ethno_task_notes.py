def _terms_from_step(step_text: str) -> list[str]:
    found: list[str] = []
    seen: set[str] = set()
    for pattern, expl in TERM_HINTS:
        if re.search(pattern, step_text, re.I):
            key = expl[:36]
            if key not in seen:
                seen.add(key)
                found.append(expl)
    return found


