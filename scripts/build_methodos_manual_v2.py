def font(run, size=10.5, bold=False, color=None, name="맑은 고딕"):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = color


def p(doc, text, *, size=10.5, bold=False, after=6, before=0, align=None, color=None):
    para = doc.add_paragraph()
    if align:
        para.alignment = align
    pf = para.paragraph_format
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    pf.line_spacing = 1.35
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    r = para.add_run(text)
    font(r, size=size, bold=bold, color=color)
    return para


def h(doc, text, level=1):
    heading = doc.add_heading(text, level=level)
    sizes = {1: 16, 2: 13, 3: 11.5, 4: 10.5}
    for run in heading.runs:
        font(run, size=sizes.get(level, 11), bold=True, color=RGBColor(0x1A, 0x1A, 0x2E))
    return heading


def bullets(doc, items, size=10):
    for it in items:
        para = doc.add_paragraph(style="List Bullet")
        para.clear()
        r = para.add_run(it)
        font(r, size=size)
        para.paragraph_format.space_after = Pt(2)
        para.paragraph_format.line_spacing = 1.25


def nums(doc, items, size=10):
    for it in items:
        para = doc.add_paragraph(style="List Number")
        para.clear()
        r = para.add_run(it)
        font(r, size=size)
        para.paragraph_format.space_after = Pt(2)


def shade(cell, fill="1A1A2E"):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    for i, hd in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        r = cell.paragraphs[0].add_run(hd)
        font(r, size=9, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
        shade(cell)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = t.rows[ri + 1].cells[ci]
            cell.text = ""
            r = cell.paragraphs[0].add_run(str(val))
            font(r, size=9)
            if ri % 2 == 1:
                shade(cell, "F4F2F7")
    doc.add_paragraph()
    return t


def note(doc, title, body):
    p(doc, f"【안내】{title}", size=10, bold=True, color=RGBColor(0x6B, 0x2D, 0x5B), after=2)
    p(doc, body, size=9.5, after=8)


